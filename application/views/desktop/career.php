	<script>

        var base_url = "<?=base_url();?>";
        drawcontens(base_url);
        function drawcontens(base_url){

            //###  ressults ###//
            var results = get_results(base_url);
            var contents = '';
            if(results.datas.length > 0){
                $.each( results.datas, function( key, val ) {
                    contents += '<div class="card">';
                    contents += '<div class="card-heading">';
                    contents += '<a data-toggle="collapse" data-target="#collapse'+val.id+'">'+val.topic+' (จำนวน '+val.counts+' ตำแหน่ง)</a>';
                    contents += '</div>';
                    contents += '<div id="collapse'+val.id+'" class="collapse" data-parent="#accordionCareer">';
                    contents += '<div class="card-body" style="padding-left: 30px;">';
                    contents += '<div class="career__qualification">';
                    contents += val.detail
                    contents += '<a href="#" class="primary-btn bg-tg">สมัครงาน</a>';
                    contents += '</div>';
                    contents += '</div>';
                    contents += '</div>';
                    contents += '</div>';
                });
                var position = '#accordionCareer';
                $(position).html(null);
                $(position).html(contents);
            }
        }
        function get_results(base_url){
            var res = null;
            $.ajax({
                url: base_url+'Main/get_career_results', //ทำงานกับไฟล์นี้
                data: '',  //ส่งตัวแปร
                type: "POST",
                dataType: 'json',
                async:false,
                success: function(data, status) {
                    res = data;
                },
                error: function(xhr, status, exception) { 
                    //console.log(xhr);
                }
            });
            return res;
        }
    </script>